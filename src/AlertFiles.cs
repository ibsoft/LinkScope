using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace LinkScope {
    // Registered directories survive crashes and directory changes. Each database has a private filename namespace.
    internal sealed class AlertFiles {
        readonly string database,owner,prefix;
        internal AlertFiles(string dbPath){
            database=dbPath;
            using(var db=new Sqlite(database,false)){
                db.Exec("CREATE TABLE IF NOT EXISTS alert_file_dirs(path TEXT PRIMARY KEY COLLATE NOCASE)");
                db.Exec("CREATE TABLE IF NOT EXISTS alert_file_owner(singleton INTEGER PRIMARY KEY CHECK(singleton=1),id TEXT NOT NULL)");
                db.Exec("INSERT OR IGNORE INTO alert_file_owner VALUES(1,?)",Guid.NewGuid().ToString("N"));
                owner=(string)db.Rows("SELECT id FROM alert_file_owner WHERE singleton=1")[0][0];
            }
            Guid guid;if(!Guid.TryParseExact(owner,"N",out guid))throw new InvalidDataException("Invalid alert file owner in SQLite.");
            prefix="LinkScope-alert-"+owner+"-";
        }
        static void CheckDirectory(string dir){
            for(var part=new DirectoryInfo(dir);part!=null;part=part.Parent){
                if(part.Exists&&(part.Attributes&FileAttributes.ReparsePoint)!=0)throw new IOException("Alert directory contains a link or junction: "+part.FullName);
            }
        }
        internal void Reconcile(DeliverySettings d){
            string dest=d.JsonEnabled?d.DirectoryPath():null;
            using(var db=new Sqlite(database,false)){
                if(dest!=null)db.Exec("INSERT OR IGNORE INTO alert_file_dirs VALUES(?)",dest);
                var paths=db.Rows("SELECT path FROM alert_file_dirs");
                Exception error=null;
                foreach(var row in paths){
                    string path=(string)row[0];bool active=string.Equals(path,dest,StringComparison.OrdinalIgnoreCase);
                    try{
                        CheckDirectory(path);
                        if(active)Directory.CreateDirectory(path);
                        var wanted=new Dictionary<string,string>(StringComparer.OrdinalIgnoreCase);
                        if(active){
                            var rows=db.Rows("SELECT "+Alerts.Columns+" FROM alert_events WHERE resolved=0 ORDER BY seq DESC LIMIT ?",d.MaxJsonFiles);
                            foreach(var eventRow in rows){
                                var a=Alerts.FromRow(eventRow);
                                // The sequence is generated by SQLite and is also valid for imported legacy alert IDs.
                                string name=prefix+a.Sequence.ToString(System.Globalization.CultureInfo.InvariantCulture)+".json";
                                wanted.Add(name,Config.Json().Serialize(new {schemaVersion=1,source="LinkScope",sourceId=owner,monitorHost=Environment.MachineName,alert=a.View(true)}));
                            }
                        }
                        Sync(path,wanted);
                        if(!active)db.Exec("DELETE FROM alert_file_dirs WHERE path=?",path);
                    }catch(DirectoryNotFoundException ex){if(active||path.StartsWith(@"\\")){if(error==null)error=ex;}else db.Exec("DELETE FROM alert_file_dirs WHERE path=?",path);}
                    catch(Exception ex){if(error==null)error=ex;}
                }
                if(error!=null)throw error;
            }
        }
        string ReadOwned(string file,long sequence,string desired){
            var info=new FileInfo(file);
            if((info.Attributes&FileAttributes.ReparsePoint)!=0||info.Length>1024*1024)throw new IOException("Unexpected existing alert file: "+file);
            string text=File.ReadAllText(file,Encoding.UTF8);
            if(text==desired)return text;
            var json=Config.Json().DeserializeObject(text) as Dictionary<string,object>;
            object id,record,number;
            var item=json!=null&&json.TryGetValue("alert",out record)?record as Dictionary<string,object>:null;
            if(json==null||!json.TryGetValue("sourceId",out id)||!Equals(id,owner)||item==null||
                !item.TryGetValue("sequence",out number)||Convert.ToInt64(number)!=sequence)throw new IOException("File ownership mismatch: "+file);
            return text;
        }
        void Sync(string path,Dictionary<string,string> wanted){
            Exception failure=null;
            foreach(string file in Directory.EnumerateFiles(path,prefix+"*.json",SearchOption.TopDirectoryOnly)){
                string name=Path.GetFileName(file);long seq;
                if(!name.EndsWith(".json",StringComparison.OrdinalIgnoreCase)||name.Length<=prefix.Length+5||
                    !long.TryParse(name.Substring(prefix.Length,name.Length-prefix.Length-5),System.Globalization.NumberStyles.None,System.Globalization.CultureInfo.InvariantCulture,out seq))continue;
                string desired;bool keep=wanted.TryGetValue(name,out desired);wanted.Remove(name);
                try{
                    string old=ReadOwned(file,seq,desired);
                    if(!keep)File.Delete(file);
                    else if(desired!=old)Publish(file,desired,true);
                }catch(Exception ex){if(failure==null)failure=ex;}
            }
            foreach(var item in wanted)try{Publish(Path.Combine(path,item.Key),item.Value,false);}
                catch(Exception ex){if(failure==null)failure=ex;}
            if(failure!=null)throw failure;
        }
        static void Publish(string file,string content,bool replace){
            string stage=file+"."+Guid.NewGuid().ToString("N")+".tmp";
            try{
                using(var f=new FileStream(stage,FileMode.CreateNew,FileAccess.Write,FileShare.None)){
                    byte[] bytes=Encoding.UTF8.GetBytes(content);f.Write(bytes,0,bytes.Length);f.Flush(true);
                }
                if(replace)File.Replace(stage,file,null);else File.Move(stage,file);
            }finally{if(File.Exists(stage))File.Delete(stage);}
        }
    }
}
